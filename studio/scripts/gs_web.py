"""Web animation engine: every shot is a render(t) page drawn on a canvas and rendered frame by frame with the
motion-showreel plugin's tools (Playwright + ffmpeg).

Code: <studio>/web/ep/<EP>/  (inside the served root; edl.py stays in <studio>/episodes/<EP>/)
    shots\\<id>.js       full-screen shots (anim / chapter / card), long video and written-short X shots
    cam\\<id>.js         CG over a camera shot (drawn on a transparent canvas, no background)
    assets\\             photos, data, SVG used by the shots (cam\\<id>.jpg = review stills, made here)
    timeline.js         generated by `sync`: SHOTS / HOLDS for the motion-showreel QA tools
Shared kit: <studio>/web/kit/ (gs.js brand pieces, themes.js house styles, house.js, intro.js, player.js, motion.js),
fonts/, brand/ (the channel's logo files, copied from the project by `sync`).
The served root is <studio>/web/ (render.mjs, editor.mjs and inspect.mjs run from there).

    python gs_web.py <EP> sync                      folders + timeline.js
    python gs_web.py <EP> render preview|final [ids] one MP4 per shot (+ <id>-matte.mp4 for camera CG)
    python gs_web.py <EP> stills <id> 0.5,3,7 [--guides]   PNG stills + contact sheet of one shot
    python gs_web.py <EP> check [ids]               determinism (same t in any order = identical pixels)
    python gs_web.py <EP> review [ids] [--short]    workspace page of these shots + their sound -> prints the
                                                    editor command (run it in the background, open the URL)
    python gs_web.py <EP> qa [--short]              motion-showreel inspect qa + motion on the built 480p
gs_episode.py calls `render` and picks the MP4s up in `build` / `short`.
"""
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

import gs_env

WEB = gs_env.STUDIO / "web"
FPS = 30
SIZE = {("preview", False): (854, 480), ("final", False): (1920, 1080),
        ("preview", True): (480, 854), ("final", True): (1080, 1920)}
KINDS = {"anim": "shots", "chapter": "shots", "card": "shots", "cam": "cam", "intro": "intro"}
INTRO_MODULE = "../../kit/intro.js"   # the channel intro (kit/intro.js), restyled by edl.INTRO_THEME (style id)


def scripts_dir():
    """The motion-showreel plugin's scripts folder: MOTION_SHOWREEL, [paths] motion_showreel, else the newest copy
    in Claude Code's plugin folders."""
    given = os.environ.get("MOTION_SHOWREEL") or gs_env.cfg("paths", "motion_showreel", "")
    roots = [Path(given)] if given else [Path.home() / ".claude" / "plugins", Path.home() / ".claude" / "skills"]
    found = []
    for r in roots:
        if (r / "scripts" / "render.mjs").exists():
            return r / "scripts"
        if r.exists():
            found += [p for p in r.rglob("scripts/render.mjs") if "motion-showreel" in p.as_posix()]
    if not found:
        raise SystemExit("the motion-showreel plugin was not found (animation engine). Install it in Claude Code:\n"
                         "  claude plugin marketplace add ConardLi/garden-skills\n  claude plugin install motion-showreel-skills@garden-skills\n"
                         "or set [paths] motion_showreel in studio.toml to its folder.")
    return sorted(found, key=lambda p: p.stat().st_mtime)[-1].parent


def web_dir(E):
    return WEB / "ep" / E.EPISODE


def style_of(E):
    """The house style of a piece: edl.CARD_THEME, else [style] house in studio.toml, else the channel palette."""
    return getattr(E, "CARD_THEME", None) or gs_env.cfg("style", "house", "") or "CHANNEL"


def channel_spec():
    """What the kit needs to know about the channel (name tag, end card, watermark, palette), from studio.toml."""
    c, b = gs_env.CHANNEL, WEB / "brand"
    return {"name": c.get("name", ""), "shortName": c.get("short_name", ""), "tagline": c.get("tagline", ""),
            "website": c.get("website", ""), "presenter": c.get("presenter", ""), "presenterTitle": c.get("presenter_title", ""),
            "subscribe": c.get("subscribe_label", "Subscribe"), "comment": c.get("comment_label", gs_env.tr("Tell me in the comments", "留言告诉我")),
            "watch": c.get("watch_label", gs_env.tr("Watch next", "推荐观看")), "chapter": c.get("chapter_label", "CHAPTER"),
            "palette": gs_env.CFG.get("palette", {}), "cjk": gs_env.CJK,
            "watermark": (b / "watermark.png").exists(), "seal": (b / "seal.png").exists()}


def brand():
    """Copy the channel's logo files from the project into web/brand (the pages only read inside the served root)."""
    b = WEB / "brand"
    b.mkdir(parents=True, exist_ok=True)
    for key, name in (("logo_watermark", "watermark.png"), ("logo_seal", "seal.png")):
        src = gs_env.PROJECT / gs_env.CHANNEL.get(key, f"brand/logo/{name}")
        if src.is_file() and (not (b / name).exists() or (b / name).stat().st_mtime < src.stat().st_mtime):
            shutil.copy2(src, b / name)


def out(E, mode, sid, matte=False):
    return E.RENDER / "videos" / "web" / mode / f"{sid}{'-matte' if matte else ''}.mp4"


def node(script, *args, check=True):
    cmd = ["node", str(scripts_dir() / script), *map(str, args)]
    r = subprocess.run(cmd, cwd=WEB, text=True, encoding="utf-8", errors="replace", capture_output=True)
    if r.returncode != 0 and check:
        print(r.stdout[-3000:], r.stderr[-3000:])
        raise SystemExit(f"failed: {script} {' '.join(map(str, args[:3]))}")
    return r


# =============================================================================== episode wiring

def scaffold(ep, kw, short=False):
    """New episode / short: its folders in web/ep/<ep> (`stubs` writes a starting module per shot after the cut)."""
    src = gs_env.STUDIO / "templates" / ("short" if short else "episode") / "web"
    dst = WEB / "ep" / ep
    dst.mkdir(parents=True, exist_ok=True)
    for f in src.rglob("*"):
        if f.is_file():
            o = dst / f.relative_to(src)
            if o.exists():
                continue                                # never overwrite shots already written
            o.parent.mkdir(parents=True, exist_ok=True)
            text = f.read_text(encoding="utf-8")
            for k, v in kw.items():
                text = text.replace("{{" + k + "}}", v)
            o.write_text(text, encoding="utf-8")
    (dst / "assets").mkdir(exist_ok=True)
    return dst


STUB_ANIM = """// {sid} · starting module in the house style (written by `gs_web.py {ep} stubs`). Replace the placeholder
// with the real drawing: keep styleBg (the style's ground), a source note (or the word for "diagram"), and the watermark.
// Drawing pieces of the house styles: kit/house.js. Beats: beat(S, 'name') from edl.py. {layout}
import {{ vis, text, sourceNote, watermark, theme }} from '../../../kit/gs.js';
import {{ styleBg }} from '../../../kit/house.js';

export default async function (S) {{
  return t => {{
    const T = theme();
    styleBg(S);
    const a = vis(t, 0.2, 0.5);
    text(S, '{sid}', S.DW / 2, S.DH * 0.42, {{ font: 'label', size: 120, weight: 700, align: 'center', color: T.muted, alpha: a * 0.5 }});
    text(S, {todo}, S.DW / 2, S.DH * 0.42 + 90, {{ size: 40, weight: 700, align: 'center', color: T.muted, alpha: a * 0.7 }});
    sourceNote(S, {diagram});
    watermark(S);
  }};
}}
"""
STUB_CAM = """// {sid} · CG over a camera shot (written by `gs_web.py {ep} stubs`). Transparent: never draw a background.
// Look at a frame first (gs_web.py {ep} review {sid}): CG never crosses the face or body.
import {{ vis, glide, nameTag, watermark }} from '../../../kit/gs.js';

export default async function (S) {{
  return t => {{
{tag}    watermark(S);
  }};
}}
"""
STUB_CHAPTER = """// {sid} · chapter card in the house style (written by `gs_web.py {ep} stubs`); the title is the script's question.
import {{ chapterCard }} from '../../../kit/gs.js';
export default async function (S) {{ return chapterCard(S, {{ number: {n}, title: {title}, en: '' }}); }}
"""
STUB_END = """// END · end card = the YouTube end screen (written by `gs_web.py {ep} stubs`).
import {{ endCard }} from '../../../kit/gs.js';
// ask = this video's question for the comments, from script.md (1-2 short lines); [] leaves it empty
export default async function (S) {{ return endCard(S, {{ ask: [] }}); }}
"""


def stubs(E):
    """A starting module in the house style for every shot that has none yet, so the chain (render, build, QA) runs
    from the first day and every shot starts from the style's ground and brand pieces. Never overwrites a module."""
    import gs_cut
    sync(E)
    title = {sid: (lines[0] if lines else sid) for sid, _, lines in gs_cut.script(E.EPISODE)}
    made, first_cam = [], {False: True, True: True}
    for s in shot_rows(E):
        if s["kind"] == "intro":
            continue
        f = web_dir(E) / KINDS[s["kind"]] / f"{s['id']}.js"
        was_first = first_cam[s["short"]] if s["kind"] == "cam" else False
        if s["kind"] == "cam":
            first_cam[s["short"]] = False
        if f.exists():
            continue
        v = vertical_of(E, s)
        if s["kind"] == "cam":
            x, y = (90, 1180) if v else (120, 760)
            tag = (f"    const tag = vis(t, 0.15, 0.4, 4.0);        // first appearance: name tag 3-5 s\n"
                   f"    nameTag(S, {x}, {y}, {{ alpha: tag, dx: -40 * (1 - glide(tag)) }});\n") if was_first else ""
            body = STUB_CAM.format(sid=s["id"], ep=E.EPISODE, tag=tag)
        elif s["kind"] == "chapter":
            body = STUB_CHAPTER.format(sid=s["id"], ep=E.EPISODE, n=int("".join(c for c in s["id"] if c.isdigit()) or 1),
                                       title=json.dumps(title.get(s["id"], s["id"]), ensure_ascii=False))
        elif s["kind"] == "card":
            body = STUB_END.format(ep=E.EPISODE)
        else:
            layout = ("Portrait 1080x1920: title band y < 360, content y 400-1330, nothing below 1360." if v else
                      "Landscape 1920x1080: nothing but subtitles below y 880.")
            body = STUB_ANIM.format(sid=s["id"], ep=E.EPISODE, layout=layout,
                                    todo=json.dumps(gs_env.tr("animation to do", "动画待做"), ensure_ascii=False),
                                    diagram=json.dumps(gs_env.CHANNEL.get("diagram_label", gs_env.tr("Diagram", "示意图")), ensure_ascii=False))
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(body, encoding="utf-8")
        made.append(f"{KINDS[s['kind']]}/{s['id']}.js")
    print("stubs written:", ", ".join(made) or "none (every shot already has a module)")


def sync(E):
    """The episode's web folders; timeline.js for the QA tools."""
    import gs_episode as G
    wd = web_dir(E)
    for d in ("shots", "cam", "assets"):
        (wd / d).mkdir(parents=True, exist_ok=True)
    brand()
    rows, holds = [], []
    for tl in [G.timeline(E)] if E.SHOTS else []:
        for s in tl:
            rows.append(f"  {{ id: '{s['id']}', kind: '{s['kind']}', t0: {s['start']:.3f}, t1: {s['end']:.3f} }},")
            if s["kind"] in ("chapter", "card", "intro"):
                holds.append(f"[{s['start']:.3f}, {s['end']:.3f}]")
    total = G.timeline(E)[-1]["end"] if E.SHOTS else 0
    (wd / "timeline.js").write_text(
        "// generated by gs_web.py sync from edl.py - do not edit (edit edl.py, rerun sync)\n"
        f"export const DUR = {total:.3f};\nexport const SHOTS = [\n" + "\n".join(rows) + "\n];\n"
        f"export const HOLDS = [{', '.join(holds)}];\nexport const DROPS = [];\n", encoding="utf-8")
    return wd


def shot_rows(E, ids=(), short=None):
    """Timeline rows of the requested shots that the web engine draws (long video first, then the X shots)."""
    import gs_episode as G
    rows = []
    for tl, is_short in ((G.timeline(E) if E.SHOTS else [], False),
                         (G.timeline(G.short_edl(E)) if E.SHORT_SHOTS else [], True)):
        if short is not None and is_short != short:
            continue
        for s in tl:
            if s["kind"] in KINDS and (not ids or s["id"] in ids):
                rows.append({**s, "short": is_short})
    return rows


def page(E, rows, name, vertical=False, review=False):
    """Write a render(t) page for these shots (played back to back) at the served root; return its path."""
    import gs_episode as G
    cue_lists = {False: E.CUES, True: G.short_edl(E).CUES if E.SHORT_SHOTS else []}
    shots, t = [], 0.0
    for s in rows:
        # the shot's subtitles in shot-local seconds, so a module can time a picture on a word with say(S, '…')
        # (the automatic cut has no hand-set beats; subtitles follow the director's corrections)
        cues = [[round(G.local(s, a), 3), round(G.local(s, b), 3), zh] for src, a, b, zh, _ in cue_lists.get(s.get("short", False), [])
                if s.get("src") and src == s["src"] and s["in"] - 0.01 <= a < s["out"]]
        mod = INTRO_MODULE if s["kind"] == "intro" else f"{KINDS[s['kind']]}/{s['id']}.js"
        if not (web_dir(E) / mod).resolve().exists():
            raise SystemExit(f"missing {web_dir(E) / mod}")
        still = f"assets/cam/{s['id']}.jpg"
        shots.append({"id": s["id"], "kind": s["kind"], "module": mod, "t0": round(t, 4), "dur": round(s["dur"], 4),
                      "beats": {k: round(v, 4) for k, v in s["beats"].items()}, "cues": cues,
                      "camStill": still if (web_dir(E) / still).exists() else None,
                      **({"theme": getattr(E, "INTRO_THEME", None) or style_of(E)} if s["kind"] == "intro" else {})})
        t += s["dur"]
    spec = {"ep": E.EPISODE, "vertical": vertical, "review": review, "shots": shots, "bust": int(time.time()),
            "cardTheme": style_of(E), "channel": channel_spec()}
    p = WEB / f"_{E.EPISODE}_{name}.html"
    p.write_text(
        f'<!doctype html><html lang="{gs_env.LANG.get("narration", "en")}"><head><meta charset="utf-8"><title>' + f"{E.EPISODE} {name}" + "</title>\n"
        '<link rel="stylesheet" href="kit/fonts.css"></head><body><canvas id="c"></canvas>\n'
        f"<script>window.GS_SPEC = {json.dumps(spec, ensure_ascii=False)};</script>\n"
        '<script type="module" src="kit/player.js"></script></body></html>\n', encoding="utf-8")
    return p


def vertical_of(E, s):
    return bool(s["short"] and E.SHORT_VERTICAL)


# =============================================================================== commands

def render(E, mode, only=()):
    """One MP4 per shot at the mode's size, 30 fps. Camera CG: a colour pass on black + a white-on-black matte."""
    sync(E)
    extra = getattr(E, "WEB_FINAL", "").split() if mode == "final" else []   # e.g. "--subframes 2 --dpr 1"
    for s in shot_rows(E, only):
        v = vertical_of(E, s)
        w, h = SIZE[(mode, v)]
        p = page(E, [s], s["id"], vertical=v)
        o = out(E, mode, s["id"])
        o.parent.mkdir(parents=True, exist_ok=True)
        node("render.mjs", p, "--size", f"{w}x{h}", "--fps", FPS, "--out", o, "--crf", 16, *extra)
        if s["kind"] == "cam":
            node("render.mjs", p, "--size", f"{w}x{h}", "--fps", FPS, "--out", out(E, mode, s["id"], True),
                 "--crf", 12, "--q", "matte=1", *extra)
        print("rendered", s["id"], o)


def stills(E, sid, times, guides=False):
    rows = shot_rows(E, (sid,))
    if not rows:
        raise SystemExit(f"{sid}: not a web shot")
    s = rows[0]
    v = vertical_of(E, s)
    p = page(E, [s], sid, vertical=v, review=True)
    w, h = SIZE[("final", v)]
    d = E.RENDER / "web-qa" / sid
    node("render.mjs", p, "--size", f"{w}x{h}", "--still", times, "--sheet", "--out", d,
         *(["--q", "guides=1"] if guides else []))
    print(d)


def check(E, ids=()):
    bad = []
    for s in shot_rows(E, ids):
        v = vertical_of(E, s)
        r = node("render.mjs", page(E, [s], s["id"], vertical=v), "--size", "%dx%d" % SIZE[("preview", v)],
                 "--determinism", check=False)
        print(s["id"], "ok" if r.returncode == 0 else "NOT deterministic")
        if r.returncode:
            bad.append(s["id"])
            print(r.stdout[-800:], r.stderr[-800:])
    raise SystemExit(1 if bad else 0)


def cam_still(E, s):
    """Review only: a graded frame from the middle of the camera clip, behind the CG."""
    import gs_episode as G
    f = web_dir(E) / "assets" / "cam" / f"{s['id']}.jpg"
    f.parent.mkdir(parents=True, exist_ok=True)
    pre = E.CAM_FRAME.get(s["src"], "")
    v = vertical_of(E, s)
    w, h = SIZE[("final", v)]
    G.ff("-ss", f"{s['in'] + min(s['dur'] / 2, 2):.3f}", "-i", E.SRC[s["src"]], "-frames:v", "1", "-vf",
         f"{pre + ',' if pre else ''}{E.CAM_GRADE},scale={w}:{h}:force_original_aspect_ratio=increase,crop={w}:{h}",
         "-q:v", "3", f)


def review(E, ids=(), short=False):
    """Workspace (motion-showreel editor) page for these shots with their sound sliced from the preview mix."""
    import gs_episode as G
    import numpy as np
    import soundfile as sf
    sync(E)
    rows = shot_rows(E, ids, short=short)
    if not rows:
        raise SystemExit("no web shots selected")
    for s in rows:
        if s["kind"] == "cam" and not (web_dir(E) / "assets" / "cam" / f"{s['id']}.jpg").exists():
            cam_still(E, s)
    if short:
        S = G.short_edl(E)
        B = E.RENDER / "build-short-preview"
        B.mkdir(parents=True, exist_ok=True)
        mix = G._mix(S, B, G.timeline(S))
    else:
        mix = G.build(E, "preview", audio_only=True)
    x, sr = sf.read(str(mix), always_2d=True)
    parts = [x[int(s["start"] * sr):int(s["start"] * sr) + int(round(s["dur"] * sr))] for s in rows]
    name = "review-short" if short else "review"
    wav = WEB / "review" / f"{E.EPISODE}-{name}.wav"     # inside the served root: the workspace refuses junctions
    wav.parent.mkdir(exist_ok=True)
    sf.write(str(wav), np.concatenate(parts), sr)
    v = bool(short and E.SHORT_VERTICAL)
    p = page(E, rows, name, vertical=v, review=True)
    w, h = SIZE[("final", v)]
    total = sum(s["dur"] for s in rows)
    print("shots:", " ".join(s["id"] for s in rows), f"({total:.1f} s)")
    print("run in the background, then open the URL it prints:")
    print(f'node "{scripts_dir() / "editor.mjs"}" "{p}" --size {w}x{h} --fps {FPS} --duration {total:.3f} '
          f'--audio review/{E.EPISODE}-{name}.wav')


def qa(E, short=False):
    """Technical checks (decode, size, fps, duration, frame count, black frames) + motion per shot (dead air,
    sudden jumps, flash frames) on the built preview. The skill's timestamped contact sheet is skipped: ffmpeg's
    drawtext can crash through fontconfig on Windows; review_frames.py makes our sheets."""
    import gs_episode as G
    B = E.RENDER / ("build-short-preview" if short else "build-preview")
    f = B / "video.mp4"
    tl = G.timeline(G.short_edl(E) if short else E)
    w, h = SIZE[("preview", bool(short and E.SHORT_VERTICAL))]
    tline = [] if short else ["--timeline", web_dir(E) / "timeline.js"]
    r = node("inspect.mjs", "qa", f, "--out", B / "qa", "--expect-size", f"{w}x{h}", "--expect-fps", FPS,
             "--expect-duration", f"{tl[-1]['end']:.2f}", "--audio", "none", *tline, check=False)
    checks = r.stdout.split("REVIEW MATERIAL")[0]
    print(checks.strip())
    m = node("inspect.mjs", "motion", f, *tline, check=False)
    print(m.stdout.strip() or m.stderr.strip())
    if " FAIL " in checks:
        raise SystemExit(1)


def main():
    import gs_episode as G
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")   # node prints · and → (cp932 console)
    if len(sys.argv) < 3:
        print(__doc__)
        return
    E = G.load(sys.argv[1])
    cmd, rest = sys.argv[2], sys.argv[3:]
    flags = {a for a in rest if a.startswith("--")}
    args = [a for a in rest if not a.startswith("--")]
    if cmd == "sync":
        print(sync(E))
    elif cmd == "stubs":
        stubs(E)
    elif cmd == "render":
        mode = args[0] if args and args[0] in ("preview", "final") else "preview"
        render(E, mode, tuple(a for a in args if a not in ("preview", "final")))
    elif cmd == "stills":
        stills(E, args[0], args[1], guides="--guides" in flags)
    elif cmd == "check":
        check(E, tuple(args))
    elif cmd == "review":
        review(E, tuple(args), short="--short" in flags)
    elif cmd == "qa":
        qa(E, short="--short" in flags)
    else:
        print(__doc__)


if __name__ == "__main__":
    main()
